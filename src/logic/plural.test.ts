import { describe, expect, it } from 'vitest';
import { daysLabel } from './plural';

describe('склонение «день»', () => {
  it.each([
    [0, '0 дней'],
    [1, '1 день'],
    [2, '2 дня'],
    [4, '4 дня'],
    [5, '5 дней'],
    [11, '11 дней'],
    [12, '12 дней'],
    [14, '14 дней'],
    [21, '21 день'],
    [22, '22 дня'],
    [25, '25 дней'],
    [111, '111 дней'],
    [101, '101 день'],
  ])('%i → %s', (n, label) => {
    expect(daysLabel(n)).toBe(label);
  });
});
